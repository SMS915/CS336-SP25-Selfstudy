import os
import argparse
import matplotlib.pyplot as plt
import numpy as np

def plot_pass_k_curve(results_list, task_name: str, show_k_list=[1, 2, 4, 8], text: bool= True):
    """
    高度优化的 Pass@k 性能对比图
    """
    # --- 1. 定义专业配色与样式配置 ---
    # 颜色字典：确保不同实验版本颜色固定，方便对比
    STYLE_CONFIG = {
        'grpo_without_std_norm': {'color': '#8B5CF6', 'z': 18, 'lw': 2.0, 'marker': 's', 'alpha': 1.0},  # 紫色
        'instruct': {'color': '#0F172A', 'z': 15, 'lw': 2.0, 'marker': 'D', 'alpha': 0.9, 'ls': '--'},  # 深蓝黑
        'drgrpo': {'color': '#E11D48', 'z': 20, 'lw': 2.2, 'marker': 'p', 'alpha': 0.8},  # 玫瑰红
        'grpo': {'color': '#F59E0B', 'z': 10, 'lw': 2.0, 'marker': 'o', 'alpha': 0.8},  # 琥珀色
        'sft': {'color': '#3B82F6', 'z': 8, 'lw': 2.0, 'marker': 'v', 'alpha': 0.7},  # 蓝色
        'baseline': {'color': '#94A3B8', 'z': 5, 'lw': 1.8, 'marker': 'h', 'alpha': 0.6},  # 灰色
        'pacs': {'color': '#009182', 'z': 22, 'lw': 2.0, 'marker': '^', 'alpha': 0.8} # 墨绿色
    }

    plt.figure(figsize=(12, 7), dpi=300)

    # 确保 show_k_list 是排序的
    show_k_list = sorted(show_k_list)
    x_labels = ['0'] + [str(k) for k in show_k_list]
    x_indices = range(len(x_labels))

    occupied_y = {i: [] for i in range(len(x_indices))}
    best_performance = 0.0
    min_distance = 4.2  # 标签纵向最小间距
    last_k = show_k_list[-1]

    # --- 2. 核心绘图循环 ---
    for result in results_list:
        name = list(result.keys())[0]
        full_data = list(result.values())[0]
        if len(full_data) == 0: continue

        # 匹配配置
        cfg = STYLE_CONFIG.get('default')
        for key in STYLE_CONFIG:
            if key in name.lower():
                cfg = STYLE_CONFIG[key]
                break

        best_performance = max(best_performance, np.max(full_data))

        # 准备显示数据
        display_data = [0.0]
        for k in show_k_list:
            if k <= len(full_data):
                display_data.append(full_data[k - 1] * 100)
            else:
                display_data.append(None)

        # 绘图
        plt.plot(x_indices, display_data,
                 marker=cfg['marker'],
                 linestyle=cfg.get('ls', '-'),
                 linewidth=cfg['lw'],
                 markersize=8 if 'no_std_norm' in name.lower() else 7,
                 label=name,
                 color=cfg['color'],
                 alpha=cfg['alpha'],
                 zorder=cfg['z'],
                 markeredgecolor='white',  # 关键：增加标记点白边
                 markeredgewidth=1.5)
        if text:

            # 标注数值标签（带避让逻辑）
            for i, val in enumerate(display_data[1:], start=1):
                if val is None: continue

                current_y = val
                attempts = 0
                while attempts < 15:
                    collision = False
                    for existing_y in occupied_y[i]:
                        if abs(current_y - existing_y) < min_distance:
                            # 如果发生碰撞，根据当前位置向上或向下偏移
                            direction = -1 if current_y > 90 else 1
                            current_y += direction * 2.5
                            collision = True
                            break
                    if not collision: break
                    attempts += 1

                occupied_y[i].append(current_y)

                # 只给核心模型或端点显示数字，避免混乱
                is_core = 'no_std_norm' in name.lower() or 'instruct' in name.lower()
                if is_core or i == len(display_data) - 1:
                    plt.text(i, current_y, f'{val:.1f}%', color=cfg['color'],
                             fontsize=9, ha='center', va='bottom', fontweight='bold',
                             bbox=dict(facecolor='white', alpha=0.7, edgecolor='none', pad=0.5))

    # --- 3. 图表美化 ---
    plt.title(f'Pass@k Performance: {task_name}', fontsize=18, fontweight='bold', pad=20, color='#1E293B')
    plt.xlabel('Number of Attempts (k)', fontsize=14, labelpad=10)
    plt.ylabel('Accuracy (%)', fontsize=14, labelpad=10)

    plt.xticks(x_indices, x_labels, fontsize=12)
    plt.yticks(range(0, 110, 10), fontsize=11, color='#64748B')

    plt.ylim(0, 105)
    plt.xlim(0.5, len(x_indices) - 0.5)

    # 柔和网格
    plt.grid(True, axis='y', linestyle='--', alpha=0.4, color='#CBD5E1')

    # 移除冗余边框
    ax = plt.gca()
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['left'].set_color('#CBD5E1')
    ax.spines['bottom'].set_color('#CBD5E1')

    # 图例处理
    loc = 'lower right' if best_performance > 0.6 else 'upper left'
    plt.legend(loc=loc, fontsize=10, frameon=True, shadow=False, borderpad=1, edgecolor='#E2E8F0')

    plt.tight_layout()

    # 保存
    save_dir = os.path.join(os.getcwd(), 'asset/')
    os.makedirs(save_dir, exist_ok=True)
    if text:
        save_name = f'{task_name}_Pass@{last_k}对比图（含PACS）.png'
    else:
        save_name = f'{task_name}_Pass@{last_k}对比图（含PACS）-无标注.png'
    save_path = os.path.join(save_dir, save_name)
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    plt.close()  # 释放内存
    print(f"图表已保存: {save_path}")

