# Calculate Retention for each model at target k values
retention_data = {}
for model in aime24_results:
    acc24 = np.array(aime24_results[model])
    acc25 = np.array(aime25_results[model])

    # Selection
    sel24 = acc24[k_indices]
    sel25 = acc25[k_indices]

    ret = []
    for a24, a25 in zip(sel24, sel25):
        if a24 == 0:
            ret.append(np.inf if a25 > 0 else 1.0)  # Handle 0/0 as 1.0 (stable but zero) or inf if jump
        else:
            ret.append(a25 / a24)
    retention_data[model] = ret

# Plot
plt.figure(figsize=(12, 7))
colors = {
    'baseline': '#94A3B8',
    'sft': '#3B82F6',
    'grpo': '#F59E0B',
    'grpo_without_std_norm': '#E11D48',
    'drgrpo': '#8B5CF6',
    'instruct': '#0F172A'
}

for model, values in retention_data.items():
    # Remove inf for plotting (or handle it)
    plot_vals = [v if v != np.inf else 3.0 for v in values]  # Cap inf at 3 for visibility
    plt.plot(k_values, plot_vals, marker='o', label=model, color=colors[model], linewidth=2)

plt.axhline(y=1.0, color='red', linestyle='--', alpha=0.6, label='Ideal Stability (100%)')
plt.xscale('log')
plt.xticks(k_values, [str(k) for k in k_values])
plt.xlabel('Attempts (k) - Log Scale')
plt.ylabel('Retention Rate (AIME 25 / AIME 24)')
plt.title('Evolution of Retention Rate with Sampling Depth (k)')
plt.legend()
plt.grid(True, which='both', linestyle=':', alpha=0.5)

plt.savefig('asset/retention_vs_k_evolution.png', dpi=300)
plt.close()

# Analysis output
for model, values in retention_data.items():
    print(f"{model}: {[round(v, 2) for v in values]}")